@pytest.fixture
def build_packet():
    """Factory fixture to build protocol packets."""
    def _build(ptype: int, seq: int, payload: bytes) -> bytes:
        def u32le(v: int) -> bytes:
            return int(v & 0xFFFFFFFF).to_bytes(4, "little")
        
        header = MAGIC + bytes([VERSION, ptype]) + u32le(seq) + u32le(len(payload))
        return header + payload
    
    return _build


